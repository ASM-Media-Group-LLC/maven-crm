-- ============================================================================
-- Scouter Daily Tasks — AI-Guided Spammer Assistant
-- ============================================================================
-- Adds a spammer task management layer on top of the existing scouter lead
-- pool. Four new Postgres tables store spammer accounts, daily assignments,
-- micro-tasks, and interaction history. A new `scouter-screenshots` storage
-- bucket holds comment proof screenshots.
--
-- All tables carry tenant_id (default current_tenant_id()) so RLS can scope
-- to the calling user's tenant. Per-user isolation is enforced via
-- auth.uid() checks for spammer-owned rows.

-- ─── 0. Add `spammer` to the app_role enum + roles_config ───────────────────

ALTER TYPE public.app_role ADD VALUE IF NOT EXISTS 'spammer';

INSERT INTO public.roles_config (name, description, is_active, is_system)
VALUES ('spammer', 'Agente de outreach en Instagram — accede únicamente al módulo Scouter Assist / Mis Tareas', true, true)
ON CONFLICT DO NOTHING;

-- ─── 1. scouter_spammer_accounts ─────────────────────────────────────────────
-- Generic Instagram accounts owned by spammer users. NOT tied to a company;
-- AI routes interactions by niche affinity at task-generation time.

CREATE TABLE public.scouter_spammer_accounts (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id           uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  instagram_handle  text NOT NULL,
  display_name      text NOT NULL,          -- "Mi cuenta fitness"
  profile_pic_url   text,
  followers_count   integer,
  bio               text,
  account_niche     text NOT NULL,          -- lifestyle, fitness, adult, business, mixed
  active            boolean NOT NULL DEFAULT true,
  last_synced_at    timestamptz,
  tenant_id         uuid NOT NULL DEFAULT public.current_tenant_id() REFERENCES public.tenants(id) ON DELETE CASCADE,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, instagram_handle)
);

CREATE INDEX idx_spammer_accounts_user   ON public.scouter_spammer_accounts(user_id) WHERE active;
CREATE INDEX idx_spammer_accounts_tenant ON public.scouter_spammer_accounts(tenant_id);

CREATE TRIGGER scouter_spammer_accounts_set_updated_at
  BEFORE UPDATE ON public.scouter_spammer_accounts
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

ALTER TABLE public.scouter_spammer_accounts ENABLE ROW LEVEL SECURITY;

-- Every authenticated user in the same tenant can read (needed for task views).
-- Writes are limited to the owning user OR admin/manager/supervisor.
CREATE POLICY "scouter_spammer_accounts_tenant_isolation" ON public.scouter_spammer_accounts
  FOR SELECT TO authenticated
  USING (tenant_id = public.current_tenant_id());

CREATE POLICY "scouter_spammer_accounts_own_or_manager" ON public.scouter_spammer_accounts
  FOR ALL TO authenticated
  USING (
    tenant_id = public.current_tenant_id()
    AND (
      user_id = auth.uid()
      OR EXISTS (
        SELECT 1 FROM public.user_roles ur
        WHERE ur.user_id = auth.uid()
          AND ur.role::text IN ('admin', 'manager', 'supervisor')
      )
    )
  )
  WITH CHECK (
    tenant_id = public.current_tenant_id()
    AND (
      user_id = auth.uid()
      OR EXISTS (
        SELECT 1 FROM public.user_roles ur
        WHERE ur.user_id = auth.uid()
          AND ur.role::text IN ('admin', 'manager', 'supervisor')
      )
    )
  );

-- ─── 2. scouter_daily_assignments ────────────────────────────────────────────
-- One row per spammer × lead × date. Generated by the daily Edge Function.
-- UNIQUE prevents duplicate assignments across runs (ON CONFLICT DO NOTHING).

CREATE TABLE public.scouter_daily_assignments (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  spammer_id     uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  lead_id        uuid NOT NULL,               -- FK to scouter_leads.id
  assigned_date  date NOT NULL DEFAULT CURRENT_DATE,
  ai_strategy    text,                        -- "warm_approach" | "cold_follow" | "multi_account" | "re_engage"
  ai_reasoning   text,                        -- Spanish explanation of why this lead
  priority       integer NOT NULL DEFAULT 5,  -- 1=highest
  status         text NOT NULL DEFAULT 'pending'
                   CHECK (status IN ('pending', 'in_progress', 'done', 'skipped')),
  tenant_id      uuid NOT NULL DEFAULT public.current_tenant_id() REFERENCES public.tenants(id) ON DELETE CASCADE,
  created_at     timestamptz NOT NULL DEFAULT now(),
  completed_at   timestamptz,
  UNIQUE (spammer_id, lead_id, assigned_date)
);

CREATE INDEX idx_daily_assignments_spammer_date ON public.scouter_daily_assignments(spammer_id, assigned_date);
CREATE INDEX idx_daily_assignments_lead         ON public.scouter_daily_assignments(lead_id);
CREATE INDEX idx_daily_assignments_tenant       ON public.scouter_daily_assignments(tenant_id);

ALTER TABLE public.scouter_daily_assignments ENABLE ROW LEVEL SECURITY;

CREATE POLICY "scouter_daily_assignments_tenant_isolation" ON public.scouter_daily_assignments
  FOR SELECT TO authenticated
  USING (tenant_id = public.current_tenant_id());

CREATE POLICY "scouter_daily_assignments_own_or_manager" ON public.scouter_daily_assignments
  FOR ALL TO authenticated
  USING (
    tenant_id = public.current_tenant_id()
    AND (
      spammer_id = auth.uid()
      OR EXISTS (
        SELECT 1 FROM public.user_roles ur
        WHERE ur.user_id = auth.uid()
          AND ur.role::text IN ('admin', 'manager', 'supervisor')
      )
    )
  )
  WITH CHECK (
    tenant_id = public.current_tenant_id()
    AND (
      spammer_id = auth.uid()
      OR EXISTS (
        SELECT 1 FROM public.user_roles ur
        WHERE ur.user_id = auth.uid()
          AND ur.role::text IN ('admin', 'manager', 'supervisor')
      )
    )
  );

-- ─── 3. scouter_interaction_tasks ────────────────────────────────────────────
-- Micro-tasks (1–4 per assignment) generated by Groq. Each task targets one
-- spammer account and prescribes a specific interaction type.

CREATE TABLE public.scouter_interaction_tasks (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  assignment_id     uuid NOT NULL REFERENCES public.scouter_daily_assignments(id) ON DELETE CASCADE,
  from_account_id   uuid NOT NULL REFERENCES public.scouter_spammer_accounts(id) ON DELETE CASCADE,
  task_type         text NOT NULL
                      CHECK (task_type IN ('follow', 'like', 'comment', 'story_view', 'story_react')),
  instruction       text NOT NULL,           -- AI-generated Spanish instruction
  suggested_comment text,                    -- Pre-written comment for comment tasks
  sort_order        integer NOT NULL DEFAULT 0,
  status            text NOT NULL DEFAULT 'pending'
                      CHECK (status IN ('pending', 'done', 'skipped')),
  screenshot_url    text,                    -- Storage path for comment proof
  completed_at      timestamptz,
  tenant_id         uuid NOT NULL DEFAULT public.current_tenant_id() REFERENCES public.tenants(id) ON DELETE CASCADE,
  created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_tasks_assignment ON public.scouter_interaction_tasks(assignment_id);
CREATE INDEX idx_tasks_tenant     ON public.scouter_interaction_tasks(tenant_id);

ALTER TABLE public.scouter_interaction_tasks ENABLE ROW LEVEL SECURITY;

CREATE POLICY "scouter_interaction_tasks_tenant_isolation" ON public.scouter_interaction_tasks
  FOR ALL TO authenticated
  USING (tenant_id = public.current_tenant_id())
  WITH CHECK (tenant_id = public.current_tenant_id());

-- ─── 4. scouter_interaction_history ──────────────────────────────────────────
-- Append-only audit log of every interaction taken by a spammer. Rows are
-- NEVER updated or deleted — only INSERT is used. Feeds cooldown logic in the
-- lead ranking SQL.

CREATE TABLE public.scouter_interaction_history (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  lead_id           uuid NOT NULL,
  spammer_id        uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  from_account_id   uuid NOT NULL REFERENCES public.scouter_spammer_accounts(id) ON DELETE CASCADE,
  interaction_type  text NOT NULL,           -- follow, like, comment, story_view, story_react
  task_id           uuid REFERENCES public.scouter_interaction_tasks(id) ON DELETE SET NULL,
  notes             text,
  tenant_id         uuid NOT NULL DEFAULT public.current_tenant_id() REFERENCES public.tenants(id) ON DELETE CASCADE,
  created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_history_lead_date ON public.scouter_interaction_history(lead_id, created_at DESC);
CREATE INDEX idx_history_spammer   ON public.scouter_interaction_history(spammer_id, created_at DESC);
CREATE INDEX idx_history_tenant    ON public.scouter_interaction_history(tenant_id);

ALTER TABLE public.scouter_interaction_history ENABLE ROW LEVEL SECURITY;

CREATE POLICY "scouter_interaction_history_tenant_isolation" ON public.scouter_interaction_history
  FOR ALL TO authenticated
  USING (tenant_id = public.current_tenant_id())
  WITH CHECK (tenant_id = public.current_tenant_id());

-- ─── 5. Storage bucket: scouter-screenshots ──────────────────────────────────
-- Private bucket. Path convention: {tenant_id}/{user_id}/{date}/{task_id}.webp
-- `(storage.foldername(name))[2]` is the second path segment = user_id.

INSERT INTO storage.buckets (id, name, public)
VALUES ('scouter-screenshots', 'scouter-screenshots', false)
ON CONFLICT (id) DO NOTHING;

-- Upload: spammer may only write to their own path segment
CREATE POLICY "scouter_screenshots_upload" ON storage.objects FOR INSERT
  TO authenticated
  WITH CHECK (
    bucket_id = 'scouter-screenshots'
    AND (storage.foldername(name))[2] = auth.uid()::text
  );

-- Read: spammer sees own files; admin/manager/supervisor see all within bucket
CREATE POLICY "scouter_screenshots_read" ON storage.objects FOR SELECT
  TO authenticated
  USING (
    bucket_id = 'scouter-screenshots'
    AND (
      (storage.foldername(name))[2] = auth.uid()::text
      OR EXISTS (
        SELECT 1 FROM public.user_roles ur
        WHERE ur.user_id = auth.uid()
          AND ur.role::text IN ('admin', 'manager', 'supervisor')
      )
    )
  );

